/**
 * Contact-form inquiries, and the outbox event type that announces one.
 *
 * `contact_inquiries` is the SYSTEM OF RECORD. That is the whole reason this
 * table exists rather than the inquiry living only as a queued notification.
 * The four reservation events are notifications ABOUT durable rows — the
 * booking survives whatever happens to the email. A contact inquiry has no
 * such row, so if the outbox were its only home, a message would be lost the
 * moment its event was abandoned after exhausting its attempts, or swept by
 * retention. A delivery queue is not an inbox.
 *
 * `notification_outbox` keeps its existing job and its existing shape: it is
 * still only the delivery queue, and nothing here renames or redesigns it.
 *
 * ---------------------------------------------------------------------------
 * THE REFERENCE, AND WHAT IT IS NOT
 *
 * Each inquiry gets its own generated public reference, unique here. The
 * outbox event will carry that reference in its existing `booking_reference`
 * column — a deliberate reuse for now, not a claim that an inquiry is a
 * booking, and explicitly not a schema change to that table.
 *
 * It is NOT duplicate-submission prevention. The reference is generated per
 * accepted submission, so a visitor who submits the same form twice produces
 * two inquiries with two references and two emails. Stopping that is an
 * application-layer concern and is not attempted here.
 *
 * A honeypot and any rate limiting likewise belong at the application layer
 * and are deliberately absent from this migration.
 *
 * ---------------------------------------------------------------------------
 * Additive. No existing table, column or row is touched; the one existing
 * constraint that changes is widened, never weakened.
 *
 * @type {import('node-pg-migrate').ColumnDefinitions | undefined}
 */
exports.shorthands = undefined;

/**
 * What a visitor may say this is about.
 *
 * Matched exactly, and in the same words, to the four options the public form
 * offers (`apps/web/features/contact/types.ts`). Stored as the label rather
 * than a code because that is what the hotel reads in the email, and a CHECK
 * over `text` rather than an enum, matching every other status-like column in
 * this schema.
 */
const INQUIRY_TYPES = [
  'Room reservation',
  'Curated journey',
  'Airport transfer',
  'General inquiry',
];

/**
 * The four reservation events, exactly as the outbox already allows them.
 *
 * Restated here so the down path below can put the constraint back precisely
 * as it was, without reading the earlier migration.
 */
const RESERVATION_EVENT_TYPES = [
  'room_reservation_created',
  'room_reservation_confirmed',
  'package_reservation_created',
  'package_reservation_confirmed',
];

/** The one event this migration adds. */
const CONTACT_EVENT_TYPE = 'contact_inquiry_received';

const EVENT_TYPE_CONSTRAINT = 'notification_outbox_event_type_check';

/**
 * Conservative caps for public input, chosen to match what this schema already
 * allows a guest to type elsewhere rather than inventing a second standard:
 *
 *   reference   64   generous for a generated token; nothing near it is real
 *   name       100   same as `reservations.guest_first_name`
 *   email      254   the RFC 5321 maximum, same as `guest_email`
 *   phone       50   same as `guest_phone`
 *   message   2000   same as `special_requests`, the existing free-text cap
 *
 * These are a backstop against abuse, not the user-facing rule: the form and
 * the request validator enforce their own limits, and a value reaching here
 * that breaks one of these means something bypassed them.
 */
const MAX_LENGTHS = {
  reference: 64,
  name: 100,
  email: 254,
  phone: 50,
  message: 2000,
};

/** `'a', 'b'` — a SQL literal list for an IN (...) predicate. */
const quoted = (values) => values.map((value) => `'${value}'`).join(', ');

/**
 * Required text: present, not blank, not padded, and within its cap.
 *
 * `~ '[^[:space:]]'` is the existing idiom for "has at least one non-space
 * character", which rejects `'   '` as firmly as `''`.
 */
const requiredText = (column, maxLength) =>
  `${column} ~ '[^[:space:]]' AND char_length(${column}) <= ${maxLength}`;

