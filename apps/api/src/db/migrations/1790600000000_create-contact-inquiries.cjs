  pgm.dropConstraint('notification_outbox', EVENT_TYPE_CONSTRAINT);
  pgm.addConstraint('notification_outbox', EVENT_TYPE_CONSTRAINT, {
    check: `event_type IN (${quoted([...RESERVATION_EVENT_TYPES, CONTACT_EVENT_TYPE])})`,
  });
